/**
 * Replaces {@code vel("...")} calls before javac attributes the compilation unit.
 * <p>
 * Each call becomes the switch expression generated by {@link JavaCodeGenerator#inlineExpression}.
 * Since attribution has not run yet, the Java variables visible at the call are read from their
 * declarations: parameters, earlier locals and fields of the enclosing classes. Their declared types
 * are attributed on a copy in the class environment and mapped by {@link ModelBoundaries} (primitives,
 * wrappers, lists, arrays, records, sizes from {@code @Dim}). A local declared with {@code var} or with
 * an unsupported type is visible but cannot be used from VEL. The expected type comes from the context:
 * a {@code return} (the method's return type), a variable initializer or an assignment to a known
 * variable; elsewhere the value keeps its own type.
 */
final class InlineRewriter extends TreeTranslator {

    static void install(JavacTask task) {
        Context context = ((BasicJavacTask) task).getContext();
        Set<CompilationUnitTree> done = Collections.newSetFromMap(new IdentityHashMap<>());
        task.addTaskListener(new TaskListener() {
            @Override
            public void started(TaskEvent e) {
                if (e.getKind() == TaskEvent.Kind.ANALYZE && done.add(e.getCompilationUnit())) {
                    JCCompilationUnit unit = (JCCompilationUnit) e.getCompilationUnit();
                    InlineRewriter rewriter = new InlineRewriter(context, unit);
                    if (rewriter.imports()) {
                        unit.defs = rewriter.translate(unit.defs);
                    }
                }
            }
        });
    }

    private final Context context;
    private final JCCompilationUnit unit;
    private final JavacTrees trees;
    /** Visible variables, innermost scope last; a null type marks a variable VEL cannot use. */
    private final Deque<Map<String, Boundary>> scopes = new ArrayDeque<>();
    /** The enclosing classes, innermost first (their environments resolve declared types). */
    private final Deque<JCClassDecl> classes = new ArrayDeque<>();
    /** Return types of the enclosing methods and lambdas (null when unknown). */
    private final Deque<Optional> returns = new ArrayDeque<>();
    private final Map<JCMethodInvocation, Boundary> targets = new IdentityHashMap<>();
    private boolean staticImport;
    private boolean classImport;

    private InlineRewriter(Context context, JCCompilationUnit unit) {
        this.context = context;
        this.unit = unit;
        this.trees = JavacTrees.instance(context);
    }

    /** Whether the unit can refer to {@code VelInline.vel} at all (by import or by its full name). */
    private boolean imports() {
        for (JCTree def : unit.defs) {
            if (def instanceof JCImport imp) {
                String name = imp.qualid.toString();
                if (imp.isStatic() && (name.equals(VelJavacPlugin.INLINE_CLASS + "." + VelJavacPlugin.INLINE_METHOD)
                        || name.equals(VelJavacPlugin.INLINE_CLASS + ".*"))) {
                    staticImport = true;
                }
                if (!imp.isStatic() && (name.equals(VelJavacPlugin.INLINE_CLASS) || name.equals("com.doubledeltas.vel.*"))) {
                    classImport = true;
                }
            }
        }
        String pkg = unit.getPackageName() == null ? "" : unit.getPackageName().toString();
        classImport |= pkg.equals("com.doubledeltas.vel");
        return true; // a fully qualified call is possible anywhere
    }

    private boolean isVelCall(JCMethodInvocation call) {
        JCExpression m = call.meth;
        if (m instanceof JCIdent id) {
            return staticImport && id.name.contentEquals(VelJavacPlugin.INLINE_METHOD);
        }
        if (m instanceof JCFieldAccess fa && fa.name.contentEquals(VelJavacPlugin.INLINE_METHOD)) {
            String owner = fa.selected.toString();
            return owner.equals(VelJavacPlugin.INLINE_CLASS) || (classImport && owner.equals("VelInline"));
        }
        return false;
    }

    // ------------------------------------------------------------------------------------------
    // Scopes
    // ------------------------------------------------------------------------------------------

    @Override
    public void visitClassDef(JCClassDecl tree) {
        classes.push(tree);
        Map<String, Boundary> fields = new HashMap<>();
        for (JCTree def : tree.defs) {
            if (def instanceof JCVariableDecl field) {
                fields.put(field.name.toString(), typeOf(field.vartype, field.mods));
            }
        }
        scopes.addLast(fields);
        returns.push(Optional.NONE);
        try {
            super.visitClassDef(tree);
        } finally {
            returns.pop();
            scopes.removeLast();
            classes.pop();
        }
    }

    @Override
    public void visitMethodDef(JCMethodDecl tree) {
        Map<String, Boundary> params = new HashMap<>();
        for (JCVariableDecl p : tree.params) {
            params.put(p.name.toString(), typeOf(p.vartype, p.mods));
        }
        scopes.addLast(params);
        returns.push(tree.restype == null ? Optional.NONE : orNone(typeOf(tree.restype, tree.mods)));
        try {
            super.visitMethodDef(tree);
        } finally {
            returns.pop();
            scopes.removeLast();
        }
    }

    @Override
    public void visitLambda(JCLambda tree) {
        Map<String, Boundary> params = new HashMap<>();
        for (JCVariableDecl p : tree.params) {
            params.put(p.name.toString(), p.vartype == null ? null : typeOf(p.vartype, p.mods));
        }
        scopes.addLast(params);
        returns.push(Optional.NONE);
        try {
            super.visitLambda(tree);
        } finally {
            returns.pop();
            scopes.removeLast();
        }
    }

    @Override
    public void visitBlock(JCBlock tree) {
        scopes.addLast(new HashMap<>());
        try {
            super.visitBlock(tree);
        } finally {
            scopes.removeLast();
        }
    }

    @Override
    public void visitForLoop(JCForLoop tree) {
        scopes.addLast(new HashMap<>());
        try {
            super.visitForLoop(tree);
        } finally {
            scopes.removeLast();
        }
    }

    @Override
    public void visitVarDef(JCVariableDecl tree) {
        if (tree.init instanceof JCMethodInvocation call && isVelCall(call)) {
            targets.put(call, typeOf(tree.vartype, tree.mods));
        }
        super.visitVarDef(tree);
        // visible from the next statement on (also re-adds fields and parameters, harmlessly)
        scopes.getLast().put(tree.name.toString(), typeOf(tree.vartype, tree.mods));
    }

    @Override
    public void visitReturn(JCReturn tree) {
        if (tree.expr instanceof JCMethodInvocation call && isVelCall(call)) {
            targets.put(call, returns.isEmpty() ? null : returns.peek().type());
        }
        super.visitReturn(tree);
    }

    @Override
    public void visitAssign(JCAssign tree) {
        if (tree.rhs instanceof JCMethodInvocation call && isVelCall(call) && tree.lhs instanceof JCIdent id) {
            targets.put(call, visible().get(id.name.toString()));
        }
        super.visitAssign(tree);
    }

    /** The usable variables visible here, the innermost declaration of each name winning. */
    private Map<String, Boundary> visible() {
        Map<String, Boundary> all = new HashMap<>();
        for (Map<String, Boundary> scope : scopes) {
            all.putAll(scope); // outer first, inner overrides
        }
        Map<String, Boundary> usable = new LinkedHashMap<>();
        all.forEach((name, type) -> {
            if (type != null) {
                usable.put(name, type);
            }
        });
        return usable;
    }

    /** A return type, with "no type known" distinct from an absent entry. */
    private record Optional(Boundary type) {
        static final Optional NONE = new Optional(null);
    }

    private static Optional orNone(Boundary type) {
        return type == null ? Optional.NONE : new Optional(type);
    }

    // ------------------------------------------------------------------------------------------
    // Rewriting
    // ------------------------------------------------------------------------------------------

    @Override
    public void visitApply(JCMethodInvocation tree) {
        if (!isVelCall(tree)) {
            super.visitApply(tree);
            return;
        }
        JCExpression replacement = rewrite(tree);
        result = replacement != null ? replacement : tree;
    }

    /** The generated expression for a {@code vel("...")} call, or null after reporting an error. */
    private JCExpression rewrite(JCMethodInvocation call) {
        if (call.args.size() != 1 || !(call.args.head instanceof JCLiteral lit) || !(lit.getValue() instanceof String source)) {
            error(call.args.isEmpty() ? call : call.args.head, "vel(...) argument must be a string literal");
            return null;
        }
        var parsed = VelFrontend.parseExpression(source);
        for (VelDiagnostic d : parsed.diagnostics()) {
            trees.printMessage(d.severity() == VelDiagnostic.Severity.ERROR ? Diagnostic.Kind.ERROR : Diagnostic.Kind.WARNING,
                    d.format(), lit, unit);
        }
        if (parsed.hasErrors()) {
            return null;
        }
        String code;
        try {
            code = JavaCodeGenerator.inlineExpressionAt(parsed.tree(), visible(), targets.get(call),
                    new ModelMethods(JavacElements.instance(context), JavacTypes.instance(context)));
        } catch (VelCompileError e) {
            error(lit, VelDiagnostic.error(e.line(), e.column(), e.getMessage()).format());
            return null;
        } catch (VelTypeException e) {
            error(lit, "VEL: " + e.getMessage());
            return null;
        }
        JCExpression expr = ParserFactory.instance(context).newParser(code, false, false, false).parseExpression();
        int pos = call.pos;
        new TreeScanner() {
            @Override
            public void scan(JCTree tree) {
                if (tree != null) {
                    tree.pos = pos; // errors in the generated code point at the vel(...) call
                    super.scan(tree);
                }
            }
        }.scan(expr);
        return expr;
    }

    private void error(JCTree at, String message) {
        trees.printMessage(Diagnostic.Kind.ERROR, message, at, unit);
    }

    // ------------------------------------------------------------------------------------------
    // Declared types
    // ------------------------------------------------------------------------------------------

    /**
     * The boundary of a declared Java type, sized by {@code @Dim}; null when VEL cannot use it.
     * Primitives and their arrays are read from the syntax; other types are attributed (see the class comment).
     */
    private Boundary typeOf(JCTree type, JCModifiers mods) {
        if (type == null) {
            return null;
        }
        List<Card> dims = null;
        JCAnnotation dim = mods == null ? null : mods.annotations.stream()
                .filter(a -> a.annotationType.toString().equals("Dim") || a.annotationType.toString().equals("com.doubledeltas.vel.Dim"))
                .findFirst().orElse(null);
        if (dim != null) {
            Map<String, int[]> values = new HashMap<>();
            for (JCExpression arg : dim.args) {
                if (arg instanceof JCAssign assign) {
                    values.put(assign.lhs.toString(), ints(assign.rhs));
                } else {
                    values.put("value", ints(arg));
                }
            }
            try {
                dims = DimSpec.fromAnnotation(values.getOrDefault("value", new int[0]),
                        values.getOrDefault("java", new int[0]), values.getOrDefault("vel", new int[0]));
            } catch (VelTypeException e) {
                error(dim, "VEL: " + e.getMessage());
                return null;
            }
        }
        Boundary b = primitive(type);
        if (b == null) {
            b = attributed(type);
        }
        if (b == null) {
            return null;
        }
        try {
            return Boundary.withDims(b, dims);
        } catch (VelTypeException e) {
            error(dim != null ? dim : type, "VEL: " + e.getMessage());
            return null;
        }
    }

    /** A primitive or an array of primitives, read from the syntax; else null. */
    private static Boundary primitive(JCTree type) {
        int rank = 0;
        JCTree t = type;
        while (t instanceof JCArrayTypeTree a) {
            t = a.elemtype;
            rank++;
        }
        if (!(t instanceof JCPrimitiveTypeTree p)) {
            return null;
        }
        ScalarType scalar = JavaTypes.ofPrimitive(p.toString());
        if (scalar == null) {
            return null; // void
        }
        return new Boundary.Direct(java.util.Collections.nCopies(rank, Card.TOP), scalar);
    }

    /** The boundary of a type attributed on a copy in the enclosing class environment; null when unsupported. */
    private Boundary attributed(JCTree type) {
        JCClassDecl owner = classes.peek();
        if (owner == null || owner.sym == null) {
            return null;
        }
        Env<AttrContext> env = Enter.instance(context).getEnv(owner.sym);
        if (env == null) {
            return null;
        }
        Log log = Log.instance(context);
        Log.DiscardDiagnosticHandler discard = new Log.DiscardDiagnosticHandler(log);
        try {
            JCTree copy = new TreeCopier<Void>(TreeMaker.instance(context)).copy(type);
            Type t = Attr.instance(context).attribType(copy, env);
            if (t == null || t.isErroneous()) {
                return null;
            }
            return new ModelBoundaries(JavacTypes.instance(context)).of(t);
        } catch (RuntimeException e) { // unsupported (VelTypeException) or not resolvable here
            return null;
        } finally {
            log.popDiagnosticHandler(discard);
        }
    }

    /** The integers of an annotation value: a literal, {@code -literal}, {@code Dim.TOP}, or an array of them. */
    private static int[] ints(JCExpression e) {
        List<JCExpression> items = e instanceof JCNewArray array ? array.elems : List.of(e);
        int[] values = new int[items.size()];
        List<JCExpression> list = new ArrayList<>(items);
        for (int i = 0; i < list.size(); i++) {
            values[i] = intValue(list.get(i));
        }
        return values;
    }

    private static int intValue(JCExpression e) {
        if (e instanceof JCLiteral lit && lit.getValue() instanceof Number n) {
            return n.intValue();
        }
        if (e instanceof JCUnary u && u.getTag() == JCTree.Tag.NEG) {
            return -intValue(u.arg);
        }
        if (e.toString().endsWith("TOP")) {
            return DimSpec.TOP;
        }
        throw new VelTypeException("@Dim sizes must be integer literals or Dim.TOP, not " + e);
    }
}
